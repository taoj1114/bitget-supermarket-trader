def build_manage_prompt(inp: "AIInput", pos: dict[str, Any]) -> str:
    pnl_pct = float(pos.get("unrealized_pnl_pct", 0))
    entry = float(pos.get("avg_entry", 0))
    last = float(inp.quote.get("lastPr", 0))
    direction = str(pos.get("direction", "long"))
    hold_days = float(pos.get("hold_days", 0))
    batches = int(pos.get("batches", 1))
    dir_label = "多头" if direction == "long" else "空头"
    lines = [
        f"持仓: {inp.symbol} [{dir_label}] 开仓价${entry:.2f}  现价${last:.2f}  "
        f"浮盈亏{pnl_pct:+.2f}%  名义${float(pos.get('notional', 0)):.1f}  "
        f"批次{batches}/3  已持有{hold_days:.1f}天(≥14天触发'清仓让位'评估)",
        f"账户: {_render_account(inp.account)}",
    ]
    # 利润保护阶梯(2026-09 用户要求: 控制好止盈止损; 只升不降, 空单镜像)
    if direction == "long":
        if pnl_pct >= 6:
            guard = f"⚠️浮盈{pnl_pct:.1f}%≥6% → 止损应上移至 成本+3% = ${entry * 1.03:.2f}(锁定大部分利润)"
        elif pnl_pct >= 4:
            guard = f"浮盈{pnl_pct:.1f}%≥4% → 止损应上移至 成本+0.5% = ${entry * 1.005:.2f}(保本线)"
        else:
            guard = f"浮盈{pnl_pct:+.1f}% < 4% → 不动止损(正常波动; 禁止因小额浮盈上移)"
    else:
        if pnl_pct >= 6:
            guard = f"⚠️浮盈{pnl_pct:.1f}%≥6% → 止损应下移至 成本-3% = ${entry * 0.97:.2f}(锁定利润)"
        elif pnl_pct >= 4:
            guard = f"浮盈{pnl_pct:.1f}%≥4% → 止损应下移至 成本-0.5% = ${entry * 0.995:.2f}(保本线)"
        else:
            guard = f"浮盈{pnl_pct:+.1f}% < 4% → 不动止损(正常波动)"
    lines.append(f"🛡 利润保护阶梯: {guard}")
    # 大盘反转防守(2026-09 用户要求): 与大盘反向的持仓应收紧
    if pos.get("market_down"):
        note = str(pos.get("market_note") or "大盘")
        if direction == "long":
            lines.append(f"⚠️ 大盘反转防守: {note} 已转 trend_down → **多单与大盘反向**: "
                         f"浮盈应及时兑现(门槛降至 2%, 不等 4~8% 目标); 浮亏若跌破短期结构(MA10/前低)立即认错")
        else:
            lines.append(f"✅ 大盘反转防守: {note} 已转 trend_down → 空单**与大盘同向**, 可继续持有; "
                         f"浮盈≥4% 按利润保护阶梯锁利")

    if inp.market_env:
        lines.insert(0, inp.market_env)
    if inp.daily_levels:
        lines.insert(1, inp.daily_levels)
    if inp.funding:
        lines.append(f"资金费率: {inp.funding}")
    lines.append(inp.ind_1d_line)
    if inp.weekly_line:
        lines.append(inp.weekly_line)
    lines.append(inp.ind_4h_line)
    lines.append(inp.ind_1h_line)
    lines.append(inp.ind_5m_line)
    lines.append(f"走势形态: {inp.trend}")
    if inp.orderbook:
        lines.append(f"盘口: {inp.orderbook}")
    if inp.news:
        lines.append(f"新闻(事实参考): {inp.news}")
    lines.append("")
    lines.append("决策步骤(内心完成): ① 日线方向还对吗(持仓方向对照) ② 位置止损清晰吗 "
                 "③ 盈利兑现还是拿住 ④ 亏损是'正常回调可等回涨'还是'买错要认错' ⑤ 资金费率/时间成本")
    lines.append("判断完毕直接输出JSON。")
    return "\n".join(lines)
